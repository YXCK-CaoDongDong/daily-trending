def apply_intl_zh(items: list[dict]) -> list[dict]:
    for row in items:
        if row.get("region") != "international":
            continue
        key = None
        for part in row.get("url", "").split("/"):
            if part.startswith("c") and len(part) > 8:
                key = part.split("?")[0]
                break
        zh = INTL_ZH.get(key or "")
        if zh:
            row["title"] = zh["title"]
            row["content"] = zh["content"]
    return items
