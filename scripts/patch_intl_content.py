def main() -> int:
    path = Path(sys.argv[1] if len(sys.argv) > 1 else "data/daily_news_2026-09-08.json")
    rows = json.loads(path.read_text(encoding="utf-8"))
    by_rank = {r["rank_no"]: r for r in rows}
    for rank, patch in INTL_PATCH.items():
        row = by_rank[rank]
        if "url" in patch:
            row["url"] = patch["url"]
        if "source" in patch:
            row["source"] = patch["source"]
        row["content"] = patch["content"]
    for rank, content in DOMESTIC_PATCH.items():
        by_rank[rank]["content"] = content
    path.write_text(
        json.dumps([by_rank[i] for i in sorted(by_rank)], ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    ok = sum(1 for r in by_rank.values() if r.get("content") and len(r["content"]) >= 80)
    print(f"Patched {path}: {ok}/50 with content>=80")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
