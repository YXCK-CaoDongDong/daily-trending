    items = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    items = [x for x in items if not DROP_DOMESTIC_TITLE.search(x.get("title", ""))]
    for row in items:
        if row.get("region") != "international":
            continue
        key = row["url"].split("?")[0]
        for url, (title, content) in ZH.items():
            if key == url.split("?")[0]:
                row["title"] = title
                row["content"] = content
                break
        else:
            # strip long English if no map
            if row.get("content") and not re.search(r"[\u4e00-\u9fff]", row["content"][:200]):
                row["content"] = ""

    # reorder: domestic first 30, intl 20
    dom = [x for x in items if x["region"] == "domestic"]
