def trim_content(text: str) -> str:
    text = text.strip()
    if len(text) <= TARGET_MAX:
        return text
    # keep first TARGET_MAX chars at paragraph boundary if possible
    cut = text[:TARGET_MAX]
    last = cut.rfind("\n")
    if last > 400:
        cut = cut[:last]
    return cut.strip()


def refetch(url: str) -> str:
    script = Path(__file__).resolve().parent / "fetch_article.py"
    proc = subprocess.run(
        [sys.executable, str(script), url],
        capture_output=True,
        text=True,
        timeout=45,
    )
    return proc.stdout.strip() if proc.returncode == 0 else ""


def main() -> int:
    in_path = Path(__file__).resolve().parents[1] / "data" / "daily_news_2026-09-26.json"
    data = json.loads(in_path.read_text(encoding="utf-8"))

    # refresh polluted domestic entries
    for row in data:
        if row["region"] == "domestic" and row["rank_no"] in {3, 6}:
            row["content"] = refetch(row["url"])

    for row in data:
        if row["region"] == "international":
            zh = TRANSLATIONS.get(row["rank_no"], "")
            row["content"] = trim_content(zh)
        elif row["content"]:
            row["content"] = trim_content(row["content"])

    in_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    filled = sum(1 for r in data if r["content"])
    intl = sum(1 for r in data if r["region"] == "international" and r["content"])
    dom = sum(1 for r in data if r["region"] == "domestic" and r["content"])
    print(f"finalized {in_path}: {filled}/50 total, domestic={dom}, international={intl}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
