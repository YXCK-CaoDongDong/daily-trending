def main() -> int:
    path = Path(sys.argv[1] if len(sys.argv) > 1 else "")
    if not path.is_file():
        print("usage: patch_intl_zh.py <json>", file=sys.stderr)
        return 1
    items = json.loads(path.read_text(encoding="utf-8"))
    for row in items:
        rank = row.get("rank_no")
        if rank in PATCH:
            row["title"] = PATCH[rank]["title"]
            row["content"] = PATCH[rank]["content"]
    path.write_text(json.dumps(items, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"patched {len(PATCH)} international rows in {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
